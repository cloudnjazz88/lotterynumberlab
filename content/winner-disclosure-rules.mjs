export function disclosureCategoryCounts(rules = WINNER_DISCLOSURE_RULES) {
  const out = {
    broad: 0,
    conditional: 0,
    temporary: 0,
    public: 0,
    no_sales: 0,
    official_guidance_not_explicit: 0,
    unresolved: 0,
  };
  for (const r of rules) {
    if (!(r.anonymityType in out)) throw new Error("Unknown category: " + r.anonymityType);
    out[r.anonymityType] += 1;
  }
  return out;
}

export function jurisdictionDirectoryRows(rules = WINNER_DISCLOSURE_RULES) {
  return [...rules].sort((a, b) => a.jurisdiction.localeCompare(b.jurisdiction));
}
